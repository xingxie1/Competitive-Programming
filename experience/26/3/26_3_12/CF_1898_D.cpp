void solve()
{
    int n;
    cin >> n;
    vt a(n),b(n);
    for (int i = 0;i < n;i++) cin >> a[i];
    for (int i = 0;i < n;i++) cin >> b[i];
    ll sum = 0;
    int mx = INT_MIN,mn = INT_MAX;
    for (int i = 0;i < n;i++)
    {
        sum += abs(a[i] - b[i]);
        mn = min(mn,max(a[i],b[i]));
        mx = max(mx,min(a[i],b[i]));
    }
    cout << sum + 2 * max(mx - mn,0) << endl;
}

