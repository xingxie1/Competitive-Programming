void solve()
{
    int n;
    cin >> n;
    vt a(n);
    for (int i = 0;i < n;i++) cin >> a[i];
    vt ans;
    vpii b;
    for (int i = 1;i < n;i++)
    {
        if (a[i] < a[i - 1]) b.push_back({a[i - 1] - a[i],i});
    }
    ranges::sort(b);
    int j = 0;
    for (int x = 1;x <= n;x++)
    {
        if (j < b.size() && x >= b[j].fi) 
        {
            ans.push_back(b[j].se + 1);
            j++;
        }
        else 
        {
            ans.push_back(n);
        }
    }
    for (int x : ans) cout << x << " ";
    cout << endl;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int _ = 1;
    cin >> _;
    while (_ --) solve();

    return 0;
}