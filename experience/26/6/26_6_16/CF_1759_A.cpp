void solve()
{
    string s;
    cin >> s;
    int n = s.size();
    auto check = [&](int st) 
    {
        string t = "Yes";
        for (int i = st;i < n;i++)
        {
            if (s[i] != t[(i - st) % 3]) return 0;
        }
        return 1;
    };
    if (n == 1)
    {
        if (s[0] == 'Y' || s[0] == 'e' || s[0] == 's') YES;
        else NO;
        return ;
    }
    if (check(0) || (s[0] == 's' && check(1)) || (s[0] == 'e' && s[1] == 's' && check(2))) YES;
    else NO;
}

