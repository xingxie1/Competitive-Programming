void solve()
{
    int n;
    cin >> n;
    vt a(n);
    for (int i = 0;i < n;i++) cin >> a[i];
    ranges::sort(a,{},[&](auto& x){return -x;});
    ll s1 = 0,s2 = 0;
    for (int i = 0;i < n;i++) 
    {
        if (i % 2 == 0 && a[i] % 2 == 0) s1 += a[i];
        if (i % 2 == 1 && a[i] % 2) s2 += a[i];
    }
    if (s1 > s2) cout << "Alice" << endl;
    else if (s1 == s2) cout << "Tie" << endl;
    else cout << "Bob" << endl;
}

