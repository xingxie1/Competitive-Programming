void solve()
{
    int n,k;
    cin >> n >> k;
    vt a(1e5 + 5);
    for (int i = 0;i < n;i++) 
    {
        int x,b;
        cin >> x >> b;
        a[x] += b;
    }
    int l = 1,r = 1;
    ll ans = 0,sum = 0;
    while (r <= 1e5)
    {
        sum += a[r];
        if (r - l + 1 > k) 
        {
            sum -= a[l++];
        }
        ans = max(ans,sum);
        r++;
    }
    cout << ans << endl;

}

