void solve()
{
    int n,k;
    cin >> n >> k;
    vvt g(n);
    for (int i = 1;i < n;i++) 
    {
        int u,v;
        cin >> u >> v;
        u--;v--;
        g[u].push_back(v);
        g[v].push_back(u);
    }
    vt sz(n);
    vt dfn(n),id(n);
    int t = 0;
    auto dfs = [&](auto&& self,int u,int fa) -> int
    {
        sz[u] = 1;
        dfn[u] = t;
        id[t] = u;
        t++;
        for (int v : g[u]) 
        {
            if (v == fa) continue;
            sz[u] += self(self,v,u); 
        }
        return sz[u];
    };
    dfs(dfs,0,-1);
    


}

