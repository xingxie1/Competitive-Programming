// 根据题目用 FenwickTree<int> t(n) 或者 FenwickTree<long long> t(n) 初始化
template<typename T = int >
class FenwickTree {
    vector<T> tree;

public:
    // 使用下标 1 到 n
    FenwickTree(int n) : tree(n + 1) {}

    // a[i] 增加 val
    // 1 <= i <= n
    // 时间复杂度 O(log n)
    void update(int i, T val) {
        for (; i < tree.size(); i += i & -i) {
            tree[i] += val;
        }
    }

    // 求前缀和 a[1] + ... + a[i]
    // 1 <= i <= n
    // 时间复杂度 O(log n)
    T pre(int i) const {
        T res = 0;
        for (; i > 0; i &= i - 1) {
            res += tree[i];
        }
        return res;
    }

    // 求区间和 a[l] + ... + a[r]
    // 1 <= l <= r <= n
    // 时间复杂度 O(log n)
    T query(int l, int r) const {
        if (r < l) {
            return 0;
        }
        return pre(r) - pre(l - 1);
    }
};
void solve()
{
    int n;
    cin >> n;
    vll s(n);
    for (int i = 0;i < n;i++) cin >> s[i];
    vt a(n);
    FenwickTree<ll> tr(n);
    for (int i = 1;i <= n;i++) tr.update(i,i);
    for (int i = n - 1;i >= 0;i--)
    {
        int l = 0,r = n + 1;
        while (l + 1 < r)
        {
            int m = l + r >> 1;
            ll sum = tr.query(1,m);
            if (sum <= s[i]) l = m;
            else r = m;
        }
        a[i] = r;
        tr.update(r,-r);
    }
    for (int x : a) cout << x << " ";
}

