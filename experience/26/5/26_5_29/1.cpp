void solve()
{
    ll l,r;
    cin >> l >> r;
    auto f = [&](ll x) -> ll
    {
        if (x % 4 == 0) return x;
        else if (x % 4 == 1) return 1LL;
        else if (x % 4 == 2) return x + 1;
        else return 0;
    };
    cout << (f(r) ^ f(l - 1)) << endl;
}

