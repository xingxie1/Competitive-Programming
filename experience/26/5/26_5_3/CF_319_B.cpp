void solve()
{
    int n;
    cin >> n;
    vt a(n);
    for (int i = 0;i < n;i++) cin >> a[i];
    int ans = 0;
    stack<pii> st;
    for (int i = a.size() - 1;i >= 0;i--) 
    {
        int cnt = 0;
        while (!st.empty() && a[i] > st.top().fi) 
        {
            cnt = max(cnt + 1,st.top().se);
            st.pop();
        }
        ans = max(ans,cnt);
        st.push({a[i],cnt});
    }
    cout << ans << endl;
}

