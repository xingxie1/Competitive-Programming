void solve()
{
    ll m,k,a1,ak;
    cin >> m >> k >> a1 >> ak;
    ll q = m / k;
    ll r = m % k;
    ll c1 = max(0LL,r - a1);
    ll c2 = max(0LL,a1 - r);
    ll c3 = max(0LL,q - ak);
    ll c4 = min(c3,c2 / k);
    cout << c1 + c3 - c4 << endl;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int _ = 1;
    cin >> _;
    while (_ --) solve();

    return 0;
}