void solve()
{
    int n;
    cin >> n;
    vt a(n);
    vll b = {0};
    for (int i = 1;i <= n;i++) b.push_back(1LL * i * i);
    for (int i = n - 1;i >= 0;i--) 
    {
        auto it = ranges::lower_bound(b,i);
        ll x = *it - i;
        for (int j = i;j >= x;j--) 
        {
            a[j] = *it - j;
        }
        i = x;
    }
    for (int x : a) cout << x << " ";
    cout << endl;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int _ = 1;
    cin >> _;
    while (_ --) solve();

    return 0;
}