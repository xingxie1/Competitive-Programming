void solve()
{
    int n;
    cin >> n;
    vt a(n);
    for (int i = 0;i < n;i++) cin >> a[i];
    vvt dp(n + 1,vt(3,INT_MIN / 2));
    dp[0][0] = 0;
    auto f = [&](int x,int y) 
    {
        if (x < y) return x + 1;
        if (x > y) return x - 1;
        return x;
    };
    for (int i = 0;i < n;i++) 
    {
        dp[i + 1][0] = f(dp[i][0],a[i]);
        dp[i + 1][1] = max(dp[i][0],dp[i][1]);
        dp[i + 1][2] = max(f(dp[i][1],a[i]),f(dp[i][2],a[i]));
    }
    cout << max(dp[n][1],dp[n][2]) << endl;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int _ = 1;
    cin >> _;
    while (_ --) solve();

    return 0;
}