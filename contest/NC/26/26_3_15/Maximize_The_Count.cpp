void solve()
{
    int n;
    cin >> n;
    vt a(n);
    for (int i = 0;i < n;i++) cin >> a[i];
    int ans = 0;
    map<int,int> cnt;
    for (int i = 0;i < n;i++)
    {
        cnt[a[i] - i]++;
    }
    for (auto[x,c] : cnt) ans = max(ans,c);
    cout << ans << endl;
}

