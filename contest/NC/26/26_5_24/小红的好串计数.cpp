void solve()
{
    int n;
    cin >> n;
    string s;
    cin >> s;
    ll ans = 0;
    int l = 0,r = 0;
    int c0 = 0,c1 = 0;
    while (r < n) 
    {
        c0 += s[r] == '0';
        c1 += s[r] == '1';
        while (c0 && c1) 
        {
            ans += n - r;
            c0 -= s[l] == '0';
            c1 -= s[l] == '1';
            l++;
        }
        r++;
    }
    cout << ans << endl;
}

