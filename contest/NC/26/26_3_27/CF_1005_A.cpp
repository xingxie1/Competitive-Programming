void solve()
{
    int n;
    cin >> n;
    vt a(n);
    for (int i = 0;i < n;i++) cin >> a[i];
    vt ans;
    for (int i = 1;i < n;i++)
    {
        if (a[i] <= a[i - 1]) ans.push_back(a[i - 1]);
    }
    if (n == 1)
    {
        cout << 1 << endl << 1;
        return ;
    }
    ans.push_back(a[n - 1]);
    cout << ans.size() << endl;
    for (int x : ans) cout << x << " ";
}

