void solve()
{
    int a,b,k;
    cin >> a >> b >> k;
    if (a > b) swap(a,b);
    int bb = b;
    int ans = INT_MAX;
    int cnt = 0;
    while (1) 
    {
        int aa = a;
        ans = min(ans,abs(b - a) + cnt);
        int c = 0;
        while (aa > b) 
        {
            aa /= k;
            c++;
            ans = min(ans,abs(b - aa) + cnt + c);
        }
        if (b == 0) break;
        b /= k;
        cnt++;
    }
    cout << ans << endl;
}

