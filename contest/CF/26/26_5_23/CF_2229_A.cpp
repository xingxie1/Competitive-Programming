void solve()
{
    int n;
    cin >> n;
    vt a(n);
    for (int i = 0;i < n;i++) cin >> a[i];
    int ans = INT_MAX;
    for (int x = 0;x <= 1000;x++) 
    {
        int mx = 0;
        for (int j = 0;j < n;j++) mx = max(mx,abs(a[j] - x));
        ans = min(ans,mx);
    }
    cout << ans << endl;
}

